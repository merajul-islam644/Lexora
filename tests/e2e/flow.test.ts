import { describe, it, expect, beforeAll } from "vitest";
import { makeTestEnv, call, createWorkspace, addEntry, sleep, type TestEnv } from "../helpers.js";

/* Full product journey (spec §22 definition of done):
 * identity → workspace → dictionary with bn/en references → generate a
 * named language → review grammar/words → use tools → export. Sign-in and
 * sign-out are Blocks hosted login now (platform-owned), so the journey
 * starts from an already-authenticated caller email. */

let env: TestEnv;
let user: string;
let wsId: string;
let generatedDrafts = 0;

beforeAll(async () => {
  env = makeTestEnv();
  user = "journey@test.dev";
});

async function pollJob(id: string): Promise<{ status: string; result: { name: string; version: number; generatedDrafts: number } | null }> {
  for (let i = 0; i < 100; i++) {
    const res = await call(env, user, "GET", `/api/ws/${wsId}/language/jobs/${id}`);
    if (res.status === 200 && ["completed", "failed", "cancelled", "timeout"].includes(res.body.status)) return res.body;
    await sleep(50);
  }
  throw new Error("job never finished");
}

describe("the full journey", () => {
  it("1. starts from an authenticated identity and creates a workspace", async () => {
    const me = await call(env, user, "GET", "/api/me");
    expect(me.status).toBe(200);
    expect(me.body.user.email).toBe(user);

    const ws = await call(env, user, "POST", "/api/workspaces", { name: "Northstar Trading" });
    expect(ws.status).toBe(201);
    wsId = ws.body.workspace.id;
  });

  it("4. builds a dictionary with Bengali + English references", async () => {
    const words: Array<[string, string, string]> = [
      ["vethra", "চুক্তি", "agreement"],
      ["solven", "গোপনীয়", "confidential"],
      ["kairum", "অনুমোদন", "approval"],
      ["dovena", "পেমেন্ট", "payment"],
      ["mirath", "সরবরাহ", "shipment"]
    ];
    for (const [word, bn, en] of words) {
      await addEntry(env, user, wsId, word, bn, en);
    }
    const dash = await call(env, user, "GET", `/api/ws/${wsId}/dashboard`);
    expect(dash.body.metrics.words).toBe(5);
    expect(dash.body.metrics.mappedPercent).toBe(100);
    expect(dash.body.language).toBeNull();
  });

  it("5. generates a named language and polls the job to completion", async () => {
    const start = await call(env, user, "POST", `/api/ws/${wsId}/language/generate`, {
      preferredName: "Nerava", style: "naturalistic", referenceLangs: "both"
    });
    expect(start.status).toBe(202);

    const job = await pollJob(start.body.jobId);
    expect(job.status).toBe("completed");
    expect(job.result!.name).toBe("Nerava");
    generatedDrafts = job.result!.generatedDrafts;
    expect(generatedDrafts).toBeGreaterThanOrEqual(20);
  });

  it("6. reviews the grammar and the language page", async () => {
    const grammar = await call(env, user, "GET", `/api/ws/${wsId}/language/grammar`);
    expect(grammar.status).toBe(200);
    expect(grammar.body.language.name).toBe("Nerava");
    for (const rule of grammar.body.rules) {
      expect(rule.explanationEnglish).toBeTruthy();
      expect(rule.explanationBengali).toBeTruthy();
    }

    const lang = await call(env, user, "GET", `/api/ws/${wsId}/language`);
    expect(lang.body.language.vocabularyCount).toBeGreaterThanOrEqual(25);
    expect(lang.body.language.warnings.length).toBeGreaterThan(0);
  });

  it("7. the dictionary now contains drafts generated by the engine", async () => {
    const list = await call(env, user, "GET", `/api/ws/${wsId}/dictionary?pageSize=100`);
    const items = list.body.items as Array<{ word: string; source: string; status: string }>;
    expect(items.length).toBe(5 + generatedDrafts);
    expect(items.filter((i) => i.source === "generated" && i.status === "draft").length).toBe(generatedDrafts);
  });

  it("8. translates a business sentence as a draft", async () => {
    const res = await call(env, user, "POST", `/api/ws/${wsId}/translate`, { text: "We will review the contract", from: "english", to: "language" });
    expect(res.status).toBe(200);
    expect(res.body.reviewStatus).toBe("draft");
    expect(res.body.mapping.length).toBeGreaterThan(2);
  });

  it("9. practices a word and sees the progress", async () => {
    const queue = await call(env, user, "GET", `/api/ws/${wsId}/practice/queue?limit=5`);
    expect(queue.status).toBe(200);
    expect(queue.body.items.length).toBeGreaterThan(0);
    expect(queue.body.stats.dueNow).toBeGreaterThan(0);

    const entryId = queue.body.items[0].entryId as string;
    const review = await call(env, user, "POST", `/api/ws/${wsId}/practice/review`, { entryId, mode: queue.body.items[0].mode, correct: true });
    expect(review.status).toBe(200);
    expect(review.body.status).toBe("learning");
  });

  it("10. the dashboard reflects real generated state", async () => {
    const dash = await call(env, user, "GET", `/api/ws/${wsId}/dashboard`);
    expect(dash.body.language.name).toBe("Nerava");
    expect(dash.body.metrics.grammarRules).toBeGreaterThanOrEqual(5);
    expect(dash.body.metrics.words).toBe(5 + generatedDrafts);
    const actions = (dash.body.activity as Array<{ action: string }>).map((a) => a.action);
    expect(actions).toContain("language.created");
  });

  it("11. exports everything and the export is audited", async () => {
    const csv = await call(env, user, "GET", `/api/ws/${wsId}/dictionary/export?format=csv`);
    expect(csv.status).toBe(200);
    const lines = String(csv.body.content).split("\n");
    expect(csv.body.content).toContain("vethra");
    expect(lines).toHaveLength(6 + generatedDrafts); // header + every word

    const activity = await call(env, user, "GET", `/api/ws/${wsId}/activity`);
    const actions = (activity.body.items as Array<{ action: string }>).map((i) => i.action);
    expect(actions).toContain("dictionary.exported");
  });
});
